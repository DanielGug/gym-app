export const getAllExercises = () => {
  return program.flatMap(day =>
    day.phases.flatMap(phase =>
      phase.exercises.map(ex => ({ ...ex, dayId: day.id, phaseId: phase.id }))
    )
  );
};

export const getExerciseById = (id) => {
  for (const day of program) {
    for (const phase of day.phases) {
      const ex = phase.exercises.find(e => e.id === id);
      if (ex) return { ...ex, dayId: day.id, phaseId: phase.id, phaseName: phase.label };
    }
  }
  return null;
};

export const getDayById = (id) => program.find(d => d.id === id);
